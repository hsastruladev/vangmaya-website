create table if not exists public.kavyas (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title_te text not null,
  title_en text not null,
  author text not null,
  year integer,
  is_public_domain boolean not null default false
);

create table if not exists public.padyalu (
  id bigint generated by default as identity primary key,
  kavya_id bigint not null references public.kavyas (id) on delete cascade,
  padyam_number integer not null check (padyam_number > 0),
  padyam_text_te text not null,
  meaning_simple_te text,
  meaning_en text,
  unique (kavya_id, padyam_number)
);

create table if not exists public.dictionary_words (
  id bigint generated by default as identity primary key,
  word_te text not null,
  meaning_te text not null,
  dictionary_name text not null,
  source_year integer not null,
  unique (word_te, dictionary_name, source_year)
);

alter table public.kavyas enable row level security;
alter table public.padyalu enable row level security;
alter table public.dictionary_words enable row level security;

create policy "Anyone can read public-domain kavyas"
  on public.kavyas for select
  to anon, authenticated
  using (is_public_domain = true);

create policy "Anyone can read padyalu from public-domain kavyas"
  on public.padyalu for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.kavyas
      where public.kavyas.id = padyalu.kavya_id
        and public.kavyas.is_public_domain = true
    )
  );

create policy "Anyone can read dictionary entries"
  on public.dictionary_words for select
  to anon, authenticated
  using (true);
